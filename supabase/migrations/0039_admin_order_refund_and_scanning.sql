-- 0039_admin_order_refund_and_scanning.sql
-- Supports manual organizer pass refunds, atomic database transitions to REFUNDED,
-- and scanner enforcement showing RED and REFUNDED for cancelled passes.

-- 1. Extend checkout_state enum with 'REFUNDED'
alter type checkout_state add value if not exists 'REFUNDED';

-- 2. Atomic procedure to process manual refund for an order and its passes/registrations
create or replace function refund_order(
  p_order_id uuid,
  p_actor_user_id uuid,
  p_reason text default 'Manual refund processed by organizers'
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order orders;
  v_passes_count integer := 0;
  v_registrations_count integer := 0;
begin
  -- 1. Lock the order row
  select * into v_order from orders where id = p_order_id for update;

  if not found then
    raise exception 'NOT_FOUND' using errcode = 'P0002';
  end if;

  -- If already refunded, return idempotent success
  if v_order.checkout_state = 'REFUNDED' then
    return jsonb_build_object(
      'refunded', true,
      'orderId', v_order.id,
      'publicOrderCode', v_order.public_order_code,
      'alreadyRefunded', true
    );
  end if;

  -- 2. Transition order state to REFUNDED
  update orders
  set checkout_state = 'REFUNDED',
      version = version + 1,
      updated_at = clock_timestamp()
  where id = p_order_id;

  -- 3. Transition all delegate passes generated by this order to REFUNDED
  with updated_passes as (
    update delegate_passes
    set state = 'REFUNDED',
        revoked_at = clock_timestamp(),
        version = version + 1,
        updated_at = clock_timestamp()
    where source_order_line_id in (
      select id from order_lines where order_id = p_order_id
    )
    returning id
  )
  select count(*) into v_passes_count from updated_passes;

  -- Revoke any QR credentials tied to these passes
  update qr_credentials
  set state = 'REVOKED',
      revoked_at = clock_timestamp()
  where delegate_pass_id in (
    select id from delegate_passes
    where source_order_line_id in (
      select id from order_lines where order_id = p_order_id
    )
  );

  -- 4. Transition all event registrations generated by this order to REFUNDED
  with updated_regs as (
    update registrations
    set state = 'REFUNDED',
        cancelled_at = clock_timestamp(),
        version = version + 1,
        updated_at = clock_timestamp()
    where order_line_id in (
      select id from order_lines where order_id = p_order_id
    )
    returning id
  )
  select count(*) into v_registrations_count from updated_regs;

  -- 5. Transition any merchandise orders generated by this order to REFUNDED
  update merchandise_orders
  set state = 'REFUNDED',
      updated_at = clock_timestamp()
  where order_id = p_order_id;

  -- 6. Mark payment records as REFUNDED
  update payments
  set disposition = 'REFUNDED',
      refunded_paise = amount_paise,
      updated_at = clock_timestamp()
  where local_order_id = p_order_id;

  -- 7. Write audit log
  perform write_audit(
    'order.refund',
    'orders',
    p_order_id::text,
    'SUCCESS',
    coalesce(p_reason, 'Manual refund processed by organizers')
  );

  return jsonb_build_object(
    'refunded', true,
    'orderId', p_order_id,
    'publicOrderCode', v_order.public_order_code,
    'passesRefunded', v_passes_count,
    'registrationsRefunded', v_registrations_count
  );
end;
$$;

-- 3. Update record_scan to check for REFUNDED pass state
drop function if exists record_scan(
  uuid, uuid, uuid, uuid, uuid, timestamptz, boolean, text, text, text, text, boolean, text
);

create or replace function record_scan(
  p_scan_id uuid,
  p_credential_jti uuid,
  p_gate_id uuid,
  p_device_id uuid,
  p_operator_user_id uuid,
  p_captured_at_device timestamptz,
  p_offline_provisional boolean,
  p_credential_state text,
  p_credential_digest text,
  p_pass_class text,
  p_masked_name text,
  p_override boolean default false,
  p_override_reason text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_gate gates;
  v_credential qr_credentials;
  v_pass delegate_passes;
  v_existing scan_attempts;
  v_attempt scan_attempts;
  v_admission admissions;
  v_scope_key text;
  v_outcome text;
  v_reason text := null;
  v_recent jsonb;
begin
  -- 0. Idempotent retry: same scan_id returns the prior recorded result.
  select * into v_existing from scan_attempts where scan_id = p_scan_id;
  if found then
    return jsonb_build_object('outcome', v_existing.outcome, 'reason', v_existing.reason_code, 'replayed', true);
  end if;

  -- 1. Gate must exist and be active for the requested p_gate_id.
  select * into v_gate from gates where id = p_gate_id;
  if not found then
    return jsonb_build_object('outcome', 'wrong_gate', 'reason', 'unknown_gate');
  end if;

  if not v_gate.is_active then
    return jsonb_build_object('outcome', 'wrong_gate', 'reason', 'gate_inactive');
  end if;

  -- 2. Device/operator must hold an active assignment to this gate.
  if not exists (
    select 1 from gate_assignments ga
    where ga.device_id = p_device_id
      and ga.gate_id = p_gate_id
      and ga.operator_user_id = p_operator_user_id
      and now() between ga.valid_from and ga.valid_until
  ) then
    return jsonb_build_object('outcome', 'wrong_gate', 'reason', 'no_active_assignment');
  end if;

  -- 3. Resolve credential
  select * into v_credential from qr_credentials where jti = p_credential_jti for update;

  if v_credential.delegate_pass_id is not null then
    select * into v_pass from delegate_passes where id = v_credential.delegate_pass_id;
  end if;

  v_scope_key := case v_gate.admission_policy
    when 'ONE_PER_DAY' then to_char(now() at time zone 'Asia/Kolkata', 'YYYY-MM-DD')
    when 'ONE_PER_EVENT' then coalesce(v_gate.linked_event_id::text, 'event')
    else 'reentry'
  end;

  if v_credential.id is null then
    v_outcome := 'unknown_credential';
  elsif p_credential_state = 'invalid_signature' then
    v_outcome := 'invalid_signature';
  elsif p_credential_state = 'refunded' or (v_pass.id is not null and v_pass.state = 'REFUNDED') then
    v_outcome := 'refunded';
    v_reason := 'pass_refunded';
  elsif v_credential.state <> 'ACTIVE' then
    v_outcome := case v_credential.state
      when 'REVOKED' then 'revoked'
      when 'EXPIRED' then 'expired'
      else 'revoked'
    end;
  elsif now() < v_credential.not_before then
    v_outcome := 'not_yet_valid';
  elsif now() > v_credential.expires_at then
    v_outcome := 'expired';
  else
    -- 4. Gate policy evaluation (existing admission for this scope).
    select * into v_admission
    from admissions
    where credential_id = v_credential.id and scope_key = v_scope_key and state = 'ACTIVE'
    for update;

    if v_admission.id is not null then
      -- 5. Existing check-in: re-entry only where the gate allows it.
      if v_gate.admission_policy = 'REENTRY_ALLOWED' then
        v_outcome := 'accepted_reentry';
      else
        v_outcome := 'duplicate';
        v_reason := 'already_admitted';
      end if;
    else
      -- 6. Event gates require a confirmed registration for the linked event.
      if v_gate.gate_type in ('EVENT', 'PRO_SHOW') and v_gate.linked_event_id is not null then
        if not exists (
          select 1
          from qr_credentials qc
          join delegate_passes dp on dp.id = qc.delegate_pass_id
          join registration_members rm on rm.user_id = dp.user_id
          where qc.id = v_credential.id
            and rm.event_id = v_gate.linked_event_id
            and exists (
              select 1 from registrations r
              where r.id = rm.registration_id and r.state = 'CONFIRMED'
            )
        ) then
          v_outcome := 'wrong_event';
          v_reason := 'no_confirmed_registration';
        end if;
      end if;

      if v_outcome is null then
        -- 7. Offline/provisional scans fail closed on FAIL_CLOSED gates
        if p_offline_provisional and v_gate.offline_policy = 'FAIL_CLOSED' and not p_override then
          v_outcome := 'cooldown';
          v_reason := 'offline_fail_closed';
        else
          v_outcome := 'accepted';
        end if;
      end if;
    end if;
  end if;

  -- 8. Supervisor override (cannot override refunded passes).
  if p_override and v_outcome not in ('accepted', 'accepted_reentry') and v_outcome <> 'refunded' then
    v_outcome := 'manual_override';
    v_reason := coalesce(p_override_reason, 'supervisor_override');
    perform write_audit('scan.override', 'gate', p_gate_id::text, 'SUCCESS', p_override_reason);
  end if;

  -- 9. Insert immutable scan attempt.
  insert into scan_attempts (
    scan_id, credential_id, device_id, operator_user_id, gate_id,
    captured_at_device, offline_provisional, outcome, reason_code, credential_digest,
    metadata
  ) values (
    p_scan_id, coalesce(v_credential.id, '00000000-0000-0000-0000-000000000000'::uuid),
    p_device_id, p_operator_user_id, v_gate.id,
    p_captured_at_device, p_offline_provisional, v_outcome, v_reason, p_credential_digest,
    jsonb_build_object('passClass', p_pass_class)
  )
  returning * into v_attempt;

  -- 10. Insert admission record on first entry (only for accepted outcomes).
  if v_outcome in ('accepted', 'manual_override') and v_credential.id is not null then
    begin
      insert into admissions (credential_id, gate_id, scope_key, first_scan_attempt_id)
      values (v_credential.id, v_gate.id, v_scope_key, v_attempt.id);
    exception when unique_violation then
      if v_gate.admission_policy = 'REENTRY_ALLOWED' then
        v_outcome := 'accepted_reentry';
        v_reason := 'race_reentry';
      else
        v_outcome := 'duplicate';
        v_reason := 'race_duplicate';
      end if;
      update scan_attempts set outcome = v_outcome, reason_code = v_reason
      where id = v_attempt.id;
    end;
  end if;

  update scanner_devices set last_seen_at = clock_timestamp() where id = p_device_id;

  -- 11. Full unified scan history across all credentials for this pass
  if v_credential.id is not null and v_credential.delegate_pass_id is not null then
    select coalesce(jsonb_agg(jsonb_build_object(
      'gateName', coalesce(g.name, 'Main Gate'), 'at', sa.captured_at_device, 'outcome', sa.outcome
    ) order by sa.captured_at_device desc), '[]'::jsonb)
    into v_recent
    from (
      select sa2.* from scan_attempts sa2
      where sa2.credential_id in (
        select qc2.id from qr_credentials qc2
        where qc2.delegate_pass_id = v_credential.delegate_pass_id
      )
      order by sa2.captured_at_device desc limit 25
    ) sa
    left join gates g on g.id = sa.gate_id;
  elsif v_credential.id is not null then
    select coalesce(jsonb_agg(jsonb_build_object(
      'gateName', coalesce(g.name, 'Main Gate'), 'at', sa.captured_at_device, 'outcome', sa.outcome
    ) order by sa.captured_at_device desc), '[]'::jsonb)
    into v_recent
    from (
      select * from scan_attempts sa2
      where sa2.credential_id = v_credential.id
      order by sa2.captured_at_device desc limit 25
    ) sa
    left join gates g on g.id = sa.gate_id;
  else
    v_recent := '[]'::jsonb;
  end if;

  return jsonb_build_object(
    'outcome', v_outcome,
    'reason', v_reason,
    'display', jsonb_build_object('maskedName', p_masked_name, 'passClass', p_pass_class),
    'recentScans', v_recent
  );
end;
$$;

-- 4. Update verify_gate_pass_lookup to support resolving REFUNDED passes
create or replace function verify_gate_pass_lookup(
  p_query text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_pass record;
  v_query text := trim(p_query);
  v_like text;
begin
  v_like := replace(replace(replace(v_query, '\', '\\'), '%', '\%'), '_', '\_');

  select
    dp.id as pass_id,
    dp.public_pass_code,
    dp.state,
    dp.activated_at,
    dp.expires_at,
    pp.name as product_name,
    pp.slug as product_slug,
    pp.is_base_pass,
    p.display_name,
    p.college_name,
    u.email
  into v_pass
  from delegate_passes dp
  join pass_products pp on pp.id = dp.pass_product_id
  join auth.users u on u.id = dp.user_id
  left join profiles p on p.user_id = dp.user_id
  where (
      dp.public_pass_code ilike v_like || '%' escape '\'
      or (
        v_query like '%@%'
        and lower(u.email) = lower(v_query)
      )
    )
  order by
    (case when dp.state = 'ACTIVE' then 1 when dp.state = 'REFUNDED' then 2 else 3 end),
    dp.created_at desc
  limit 1;

  if not found then
    return jsonb_build_object('found', false);
  end if;

  return jsonb_build_object(
    'found', true,
    'passId', v_pass.pass_id,
    'publicPassCode', v_pass.public_pass_code,
    'state', v_pass.state,
    'productName', v_pass.product_name,
    'productSlug', v_pass.product_slug,
    'isBasePass', v_pass.is_base_pass,
    'displayName', v_pass.display_name,
    'collegeName', v_pass.college_name,
    'email', v_pass.email,
    'activatedAt', v_pass.activated_at,
    'expiresAt', v_pass.expires_at
  );
end;
$$;
