#!/usr/bin/env bash
#
# deploy.sh — promote an immutable image digest to this origin (plan §15.9).
#
# Usage:
#   PULSE_IMAGE=registry.example.com/pulse@sha256:... ./deploy.sh
#
# Steps:
#   1. Pull the exact digest (never a mutable tag).
#   2. Start the candidate containers.
#   3. Wait for web readiness via /api/health/ready.
#   4. Validate nginx config, then atomic reload.
#   5. Drain the previous containers after a grace period.
#
# Rollback: ./rollback.sh (re-points compose at the previous digest).
#
# PULSE_SKIP_PULL=1 skips step 1 for an image built on this host rather than
# pulled from a registry (see deploy-local.sh). The image must already exist
# locally; everything after the pull is identical.

set -euo pipefail

IMAGE="${PULSE_IMAGE:?PULSE_IMAGE must be set to an image digest}"
COMPOSE_FILE="${COMPOSE_FILE:-docker-compose.yml}"
READY_TIMEOUT="${READY_TIMEOUT:-60}"
DRAIN_SECONDS="${DRAIN_SECONDS:-20}"
STATE_DIR="${STATE_DIR:-/var/lib/pulse}"
NGINX_UPSTREAM_CONF="${NGINX_UPSTREAM_CONF:-/etc/nginx/conf.d/pulse-upstream.conf}"

mkdir -p "$STATE_DIR"

if [ "${PULSE_SKIP_PULL:-0}" = "1" ]; then
  echo "==> Skipping pull (PULSE_SKIP_PULL=1); using host-built $IMAGE"
  # Fail fast rather than letting compose start a stale image.
  docker image inspect "$IMAGE" > /dev/null
else
  echo "==> Pulling $IMAGE"
  docker pull "$IMAGE"
fi

# Run database migrations before starting new image containers if credentials exist
if [ -f ".env" ] || [ -f ".env.local" ] || [ -n "${SUPABASE_DB_SESSION_URL:-}" ] || [ -n "${SUPABASE_DB_DIRECT_URL:-}" ]; then
  echo "==> Running database migrations"
  if ! command -v pnpm >/dev/null 2>&1; then
    echo "!! Database credentials detected but 'pnpm' is not installed on this host." >&2
    echo "!! Cannot apply migrations — aborting deploy to prevent schema drift." >&2
    exit 1
  fi
  pnpm db:apply --migrations || {
    echo "!! Database migrations failed — aborting deploy." >&2
    exit 1
  }
fi

# ---------------------------------------------------------------------------
# Blue / Green slot resolution
# ---------------------------------------------------------------------------
ACTIVE_SLOT="blue"
if [ -f "$STATE_DIR/active-slot" ]; then
  ACTIVE_SLOT="$(cat "$STATE_DIR/active-slot")"
fi

if [ "$ACTIVE_SLOT" = "blue" ]; then
  CANDIDATE_SLOT="green"
  CANDIDATE_SERVICE="web-green"
  CANDIDATE_PORT=3002
  OLD_SERVICE="web-blue"
  OLD_PORT=3001
else
  CANDIDATE_SLOT="blue"
  CANDIDATE_SERVICE="web-blue"
  CANDIDATE_PORT=3001
  OLD_SERVICE="web-green"
  OLD_PORT=3002
fi

CANDIDATE_READY_URL="${READY_URL:-http://127.0.0.1:${CANDIDATE_PORT}/api/health/ready}"

echo "==> Active slot: $ACTIVE_SLOT (service: $OLD_SERVICE)"
echo "==> Deploying candidate to slot: $CANDIDATE_SLOT (service: $CANDIDATE_SERVICE, port: $CANDIDATE_PORT)"

rollback_on_failure() {
  echo "!! Candidate failed readiness or nginx validation — tearing down candidate $CANDIDATE_SERVICE..." >&2
  docker compose -f "$COMPOSE_FILE" stop "$CANDIDATE_SERVICE" 2>/dev/null || true
  if [ -f "$STATE_DIR/previous-image" ] && [ -f "$(dirname "$0")/rollback.sh" ]; then
    echo "!! Active slot $ACTIVE_SLOT was never switched. Stack remains on current production image." >&2
  fi
  exit 1
}

# ---------------------------------------------------------------------------
# Start candidate web container
# ---------------------------------------------------------------------------
DEPLOYMENT_ID="${DEPLOYMENT_ID:-$(echo "$IMAGE" | sed -E 's/.*[:@]//' | cut -c1-12)}"
echo "==> Starting candidate container ($CANDIDATE_SERVICE) [DEPLOYMENT_ID: $DEPLOYMENT_ID]"
DEPLOYMENT_ID="$DEPLOYMENT_ID" PULSE_IMAGE="$IMAGE" docker compose -f "$COMPOSE_FILE" up -d --no-deps "$CANDIDATE_SERVICE"

echo "==> Waiting for candidate readiness ($CANDIDATE_READY_URL)"
deadline=$(( $(date +%s) + READY_TIMEOUT ))
until curl -fsS "$CANDIDATE_READY_URL" > /dev/null 2>&1; do
  if [ "$(date +%s)" -gt "$deadline" ]; then
    echo "!! Candidate readiness check failed on port $CANDIDATE_PORT — inspect 'docker compose logs $CANDIDATE_SERVICE'" >&2
    rollback_on_failure
  fi
  sleep 2
done
echo "==> Candidate $CANDIDATE_SERVICE is healthy and ready on port $CANDIDATE_PORT"

# ---------------------------------------------------------------------------
# Switch Nginx Upstream to Candidate (Atomic Cutover)
# ---------------------------------------------------------------------------
UPSTREAM_TMP="$(mktemp)"
cat <<EOF > "$UPSTREAM_TMP"
# PULSE 2026 — dynamic blue/green upstream definition.
# Auto-generated by deploy.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Active slot: $CANDIDATE_SLOT (port $CANDIDATE_PORT)

upstream next_app {
    server 127.0.0.1:${CANDIDATE_PORT} max_fails=3 fail_timeout=10s;
    keepalive 32;
}
EOF

if command -v nginx >/dev/null 2>&1; then
  echo "==> Updating Nginx upstream to port $CANDIDATE_PORT"
  mkdir -p "$(dirname "$NGINX_UPSTREAM_CONF")"
  cp "$UPSTREAM_TMP" "$NGINX_UPSTREAM_CONF"
  rm -f "$UPSTREAM_TMP"

  echo "==> Validating Nginx config"
  if ! nginx -t; then
    echo "!! Nginx config validation failed after switching upstream" >&2
    rollback_on_failure
  fi

  echo "==> Reloading Nginx (atomic cutover to $CANDIDATE_SLOT)"
  nginx -s reload
else
  echo "==> Nginx command not present; wrote upstream config to $(dirname "$0")/../nginx/conf.d/pulse-upstream.conf"
  cp "$UPSTREAM_TMP" "$(dirname "$0")/../nginx/conf.d/pulse-upstream.conf"
  rm -f "$UPSTREAM_TMP"
fi

# ---------------------------------------------------------------------------
# Start / Update background worker
# ---------------------------------------------------------------------------
echo "==> Updating background worker service"
DEPLOYMENT_ID="$DEPLOYMENT_ID" PULSE_IMAGE="$IMAGE" docker compose -f "$COMPOSE_FILE" up -d --no-deps worker

# ---------------------------------------------------------------------------
# Graceful connection drain of old web slot
# ---------------------------------------------------------------------------
echo "==> Draining old connections on $OLD_SERVICE for ${DRAIN_SECONDS}s"
sleep "$DRAIN_SECONDS"

echo "==> Stopping old slot ($OLD_SERVICE)"
docker compose -f "$COMPOSE_FILE" stop "$OLD_SERVICE" 2>/dev/null || true

# Surface the compose healthcheck outcome in the deploy result (D10): the
# deploy decision is gated on the app-ready endpoint, but a container marked
# `unhealthy` by the compose healthcheck is a signal worth knowing about.
ACTIVE_CID="$(docker compose -f "$COMPOSE_FILE" ps -q "$CANDIDATE_SERVICE" 2>/dev/null || true)"
HEALTH="$(docker inspect --format='{{if .State.Health}}{{.State.Health.Status}}{{else}}none{{end}}' "$ACTIVE_CID" 2>/dev/null || true)"
if [ -n "$HEALTH" ] && [ "$HEALTH" = "unhealthy" ]; then
  echo "!! WARN: $CANDIDATE_SERVICE reports compose health='unhealthy' despite a passing ready endpoint — investigate (docker compose -f $COMPOSE_FILE logs $CANDIDATE_SERVICE)." >&2
fi

# ---------------------------------------------------------------------------
# Record state & audit log
# ---------------------------------------------------------------------------
if [ -f "$STATE_DIR/current-image" ]; then
  cp "$STATE_DIR/current-image" "$STATE_DIR/previous-image"
fi
printf '%s' "$IMAGE" > "$STATE_DIR/current-image"
printf '%s' "$CANDIDATE_SLOT" > "$STATE_DIR/active-slot"
echo "$(date -u +%Y-%m-%dT%H:%M:%SZ) DEPLOY slot=$CANDIDATE_SLOT image=$IMAGE" >> "$STATE_DIR/deploy-history.log"

echo "==> Deploy complete (Zero Downtime): $IMAGE active on slot $CANDIDATE_SLOT (port $CANDIDATE_PORT)"
