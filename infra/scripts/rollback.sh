#!/usr/bin/env bash
#
# rollback.sh — re-point this origin at the previous image digest
# (plan §15.9 step 14: retain previous digests for rollback).
#
# Usage: ./rollback.sh

set -euo pipefail

COMPOSE_FILE="${COMPOSE_FILE:-docker-compose.yml}"
READY_TIMEOUT="${READY_TIMEOUT:-60}"
DRAIN_SECONDS="${DRAIN_SECONDS:-10}"
STATE_DIR="${STATE_DIR:-/var/lib/pulse}"
NGINX_UPSTREAM_CONF="${NGINX_UPSTREAM_CONF:-/etc/nginx/conf.d/pulse-upstream.conf}"

PREV_FILE="$STATE_DIR/previous-image"
IMAGE="${1:-}"

if [ -z "$IMAGE" ]; then
  if [ ! -f "$PREV_FILE" ]; then
    echo "!! No previous image recorded in $PREV_FILE and no digest specified." >&2
    echo "!! Usage: ./rollback.sh [optional-image-digest]" >&2
    exit 1
  fi
  IMAGE="$(cat "$PREV_FILE")"
fi

# Refuse a no-op flip-flop: the state machine keeps one previous image per
# deploy, so a second rollback without an explicit digest would re-deploy the
# image we just rolled away from. Requiring an explicit digest here makes the
# operator state intent (D5).
if [ -f "$STATE_DIR/current-image" ]; then
  CURRENT="$(cat "$STATE_DIR/current-image")"
  if [ -n "$CURRENT" ] && [ "$IMAGE" = "$CURRENT" ]; then
    echo "!! Refusing no-op rollback: $IMAGE is already the active image." >&2
    echo "!! Rollback history is one deploy deep; pass an explicit digest to force a different image." >&2
    exit 1
  fi
fi

echo "==> Rolling back to $IMAGE"

if ! docker pull "$IMAGE" 2>/dev/null; then
  if docker image inspect "$IMAGE" > /dev/null 2>&1; then
    echo "==> Pull unavailable; using local image $IMAGE"
  else
    echo "!! Cannot pull $IMAGE and it is not present locally — nothing to roll back to." >&2
    exit 1
  fi
fi

# ---------------------------------------------------------------------------
# Blue / Green slot resolution
# ---------------------------------------------------------------------------
ACTIVE_SLOT="blue"
if [ -f "$STATE_DIR/active-slot" ]; then
  ACTIVE_SLOT="$(cat "$STATE_DIR/active-slot")"
fi

if [ "$ACTIVE_SLOT" = "blue" ]; then
  CANDIDATE_SLOT="green"
  CANDIDATE_SERVICE="web-green"
  CANDIDATE_PORT=3002
  OLD_SERVICE="web-blue"
  OLD_PORT=3001
else
  CANDIDATE_SLOT="blue"
  CANDIDATE_SERVICE="web-blue"
  CANDIDATE_PORT=3001
  OLD_SERVICE="web-green"
  OLD_PORT=3002
fi

CANDIDATE_READY_URL="${READY_URL:-http://127.0.0.1:${CANDIDATE_PORT}/api/health/ready}"

echo "==> Starting rollback candidate on slot $CANDIDATE_SLOT ($CANDIDATE_SERVICE, port $CANDIDATE_PORT)"
PULSE_IMAGE="$IMAGE" docker compose -f "$COMPOSE_FILE" up -d --no-deps "$CANDIDATE_SERVICE"

echo "==> Waiting for readiness ($CANDIDATE_READY_URL)"
deadline=$(( $(date +%s) + READY_TIMEOUT ))
until curl -fsS "$CANDIDATE_READY_URL" > /dev/null 2>&1; do
  if [ "$(date +%s)" -gt "$deadline" ]; then
    echo "!! Rollback readiness check failed on port $CANDIDATE_PORT — investigate manually." >&2
    docker compose -f "$COMPOSE_FILE" stop "$CANDIDATE_SERVICE" 2>/dev/null || true
    exit 1
  fi
  sleep 2
done

# ---------------------------------------------------------------------------
# Atomic Nginx Cutover
# ---------------------------------------------------------------------------
UPSTREAM_TMP="$(mktemp)"
cat <<EOF > "$UPSTREAM_TMP"
# PULSE 2026 — dynamic blue/green upstream definition.
# Auto-generated by rollback.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Active slot: $CANDIDATE_SLOT (port $CANDIDATE_PORT)

upstream next_app {
    server 127.0.0.1:${CANDIDATE_PORT} max_fails=3 fail_timeout=10s;
    keepalive 32;
}
EOF

if command -v nginx >/dev/null 2>&1; then
  mkdir -p "$(dirname "$NGINX_UPSTREAM_CONF")"
  cp "$UPSTREAM_TMP" "$NGINX_UPSTREAM_CONF"
  rm -f "$UPSTREAM_TMP"
  nginx -t
  nginx -s reload
else
  cp "$UPSTREAM_TMP" "$(dirname "$0")/../nginx/conf.d/pulse-upstream.conf"
  rm -f "$UPSTREAM_TMP"
fi

echo "==> Updating background worker service to $IMAGE"
PULSE_IMAGE="$IMAGE" docker compose -f "$COMPOSE_FILE" up -d --no-deps worker

echo "==> Draining old connections for ${DRAIN_SECONDS}s"
sleep "$DRAIN_SECONDS"

docker compose -f "$COMPOSE_FILE" stop "$OLD_SERVICE" 2>/dev/null || true

# ---------------------------------------------------------------------------
# Record state
# ---------------------------------------------------------------------------
printf '%s' "$IMAGE" > "$STATE_DIR/current-image"
printf '%s' "$CANDIDATE_SLOT" > "$STATE_DIR/active-slot"
echo "$(date -u +%Y-%m-%dT%H:%M:%SZ) ROLLBACK slot=$CANDIDATE_SLOT image=$IMAGE" >> "$STATE_DIR/deploy-history.log"

echo "==> Rollback complete (Zero Downtime): $IMAGE active on slot $CANDIDATE_SLOT"
